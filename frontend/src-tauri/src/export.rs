// File export commands (e.g. meeting notes rendered to PDF by the frontend)

use log::info;
use tauri::{AppHandle, Runtime};
use tauri_plugin_dialog::DialogExt;

/// Characters not allowed in file names on at least one supported platform
fn sanitize_file_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| match c {
            '/' | '\\' | ':' | '*' | '?' | '"' | '<' | '>' | '|' => '-',
            c if c.is_control() => ' ',
            c => c,
        })
        .collect();
    let trimmed = cleaned.trim().trim_matches('.');
    if trimmed.is_empty() {
        "meeting".to_string()
    } else {
        trimmed.chars().take(120).collect()
    }
}

/// Ask where to save a PDF generated by the frontend and write it there.
/// Returns the saved path, or None if the user cancelled the dialog.
#[tauri::command]
pub async fn save_pdf_file<R: Runtime>(
    app: AppHandle<R>,
    file_name: String,
    bytes: Vec<u8>,
) -> Result<Option<String>, String> {
    let default_name = format!("{}.pdf", sanitize_file_name(&file_name));
    let dialog_app = app.clone();
    let picked = tokio::task::spawn_blocking(move || {
        let mut dialog = dialog_app
            .dialog()
            .file()
            .add_filter("PDF", &["pdf"])
            .set_file_name(&default_name);
        if let Some(documents) = dirs::document_dir() {
            dialog = dialog.set_directory(documents);
        }
        dialog.blocking_save_file()
    })
    .await
    .map_err(|e| format!("Save dialog failed: {}", e))?;

    let Some(path) = picked else {
        return Ok(None);
    };
    let mut path = path
        .into_path()
        .map_err(|e| format!("Invalid save location: {}", e))?;
    if path.extension().is_none() {
        path.set_extension("pdf");
    }

    tokio::fs::write(&path, &bytes)
        .await
        .map_err(|e| format!("Failed to write {}: {}", path.display(), e))?;
    info!("Exported PDF ({} bytes) to {}", bytes.len(), path.display());
    Ok(Some(path.to_string_lossy().to_string()))
}

#[cfg(test)]
mod tests {
    use super::sanitize_file_name;

    #[test]
    fn sanitizes_file_names() {
        assert_eq!(sanitize_file_name("Họp: Q3/Q4 *plan*"), "Họp- Q3-Q4 -plan-");
        assert_eq!(sanitize_file_name("  ..  "), "meeting");
        assert_eq!(sanitize_file_name("会议纪要"), "会议纪要");
    }
}
